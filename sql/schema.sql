-- =============================================================================
-- 业务不变量：一人一天一单（有效订单）
-- 服务层已按 (employee_id, order_date) 校验，但并发下仍可能同时通过；
-- 这里用“部分唯一索引”把约束落到数据库层：
--   * 只约束 PENDING / VALID（有效订单），已取消、已作废不占名额，员工可以重新下单；
--   * 不能用普通唯一约束，否则同一员工同一天出现“取消后再下单”会被误杀。
-- =============================================================================
create unique index if not exists uk_order_form_employee_date_active
	on order_form (employee_id, order_date)
	where status in ('PENDING', 'VALID');
