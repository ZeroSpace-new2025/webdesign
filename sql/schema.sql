	offline_reason	varchar(200),
	version			integer			not null,
	created_by		bigint,
	created_at		timestamp(6),
	updated_at		timestamp(6),
	primary key (recipe_id),
	constraint ck_recipe_status check (status in ('ACTIVE', 'DISABLED'))
);

