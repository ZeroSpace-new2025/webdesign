-- -----------------------------------------------------------------------------
-- recipe：菜品（食谱）标准信息。修改/下架只影响未来菜单，历史菜单与订单靠快照保护。
-- -----------------------------------------------------------------------------
create table if not exists recipe (
	recipe_id		bigint generated by default as identity,
	recipe_name		varchar(100)	not null,
	category		varchar(50),
	unit			varchar(20),
	unit_price		numeric(10, 2)	not null,
